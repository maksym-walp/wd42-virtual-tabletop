-- ================================================================
-- Прев'ю-зображення мапи для карток у каталозі (/maps) та в кампаніях.
-- Окреме від шарів (map_lenses): шари — це повнорозмірні зображення мапи
-- (часто десятки МБ), а прев'ю — довільна обкладинка, яку власник
-- завантажує сам. Як і в 57-equipment-thumbnail-url.sql, зберігаємо пару:
-- оригінал (для бічної панелі перегляду) і 400px webp-мініатюру (для сітки).
-- ================================================================

ALTER TABLE maps.maps
    ADD COLUMN IF NOT EXISTS preview_image_url     VARCHAR(500),
    ADD COLUMN IF NOT EXISTS preview_thumbnail_url VARCHAR(500);
