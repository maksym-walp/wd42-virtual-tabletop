-- ================================================================
-- Хронологія: синхронізація календарів із календарем за замовчуванням.
--
-- sync_offset_days — зсув у днях між лічбою днів цього календаря
-- (totalDaysSinceEpoch: день 1 року 1 = 0) і спільною «світовою» віссю:
--   світовий_день = день_у_календарі − sync_offset_days.
-- Вісь прив'язана до календаря, який був основним, коли синхронізацію
-- задавали, тож зміна календаря за замовчуванням її не ламає (див.
-- ChronologyModel.setDefault). NULL — календар не синхронізовано, події
-- інших календарів у ньому не показуються, а його події — в інших. Сам
-- календар за замовчуванням завжди має значення (0, якщо його не задавали).
-- Задається парою дат («ця мить у цьому календарі = ця мить в основному»),
-- яку інтерфейс перетворює на зсув.
--
-- Подія належить календарю (calendar_events.calendar_id), за структурою
-- якого рахується її повторюваність, а на сітках усіх синхронізованих
-- календарів показується через цю вісь.
-- ================================================================

ALTER TABLE chronology.calendars
    ADD COLUMN IF NOT EXISTS sync_offset_days INT;

UPDATE chronology.calendars SET sync_offset_days = 0 WHERE is_default AND sync_offset_days IS NULL;
