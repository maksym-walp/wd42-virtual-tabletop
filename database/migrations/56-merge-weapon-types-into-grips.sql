-- ================================================================
-- "Особливості зброї" (weapon_grips) розширюються ключами з "Типів зброї"
-- (weapon_types) в один спільний список варіантів для поля "Особливості" на
-- формі зброї — замість окремого хвата (одноручна/дворучна) і типу
-- (ближня/дальня/метальна/універсальна/інше) адмін тримає їх разом.
--
-- Ключ 'versatile' (Універсальна) зникає з набору — його місце займає
-- однойменний 'universal' із weapon_types (той самий label "Універсальна"),
-- тож зброя, що мала обраним 'versatile', переноситься на 'universal', щоб
-- вибір не загубився.
--
-- weapon_types лишається без змін (досі окремий список для поля "Тип
-- зброї") — цей файл торкається лише weapon_grips (конфіга і даних).
-- ================================================================

UPDATE admin.site_configs
SET value = '[
        {"key":"one_handed","label":"Одноручна"},
        {"key":"two_handed","label":"Дворучна"},
        {"key":"melee","label":"Ближня"},
        {"key":"ranged","label":"Дальньобійна"},
        {"key":"thrown","label":"Метальна"},
        {"key":"universal","label":"Універсальна"},
        {"key":"other","label":"Інше"}
    ]'::jsonb,
    updated_at = NOW()
WHERE key = 'weapon_grips';

-- Зброя, що мала стару 'versatile' — переносимо вибір на 'universal', щоб
-- запис і далі показував обраний варіант (обидва мали той самий label
-- "Універсальна", тож для гравця нічого не змінюється).
UPDATE equipment.weapons
SET weapon_grip = array_replace(weapon_grip, 'versatile', 'universal')
WHERE weapon_grip IS NOT NULL AND 'versatile' = ANY(weapon_grip);
