-- Масштаб мапи (рулетка): власник задає еталонний відрізок — дві точки на
-- зображенні активного на момент калібрування шару (нормалізовані 0..1,
-- конвертовані в піксельні на клієнті) + реальну відстань у км. З цього
-- виводиться km-per-pixel.
--
-- Шари можуть мати різний пікс. розмір зображення, але спільне
-- співвідношення сторін (мітки рендеряться консистентно в нормалізованих
-- координатах на будь-якому шарі) — тож зберігаємо РАЗОМ із km-per-pixel
-- пікс. ширину/висоту зображення, яке було активним під час калібрування
-- (scale_reference_width/height). Конвертація normalized→км на клієнті
-- завжди множить на ЦІ збережені референсні розміри, а не на натуральні
-- піксельні розміри поточного (можливо, іншого) шару — інакше масштаб
-- "зсувався" б при перемиканні шарів різної роздільності.
--
-- Усі три поля NULL разом (не задано) або всі три задані (all-or-nothing,
-- перевіряється в контролері, не в БД).
ALTER TABLE maps.maps
    ADD COLUMN IF NOT EXISTS scale_km_per_pixel    DOUBLE PRECISION,
    ADD COLUMN IF NOT EXISTS scale_reference_width  INTEGER,
    ADD COLUMN IF NOT EXISTS scale_reference_height INTEGER;
