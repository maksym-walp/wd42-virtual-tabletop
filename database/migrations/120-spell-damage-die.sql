-- ================================================================
-- Кубик шкоди заклинання — для «бойових» заклинань (spell_kind =
-- 'combat', міграція 116), які завдають шкоди ціли під час атаки.
--
-- Той самий формат, що й equipment_items.damage_die/
-- campaigns.combatants.damage_die: один рядок рангу ('d4'..'d12'),
-- NULL — заклинання без шкоди (наприклад, силовий поштовх). Кількість
-- кубиків НЕ зберігається тут — вона завжди береться з Майстерності
-- кастера (roll_profiles.damage_dice.count, розділ 4.4.3 книги
-- правил), як і для зброї; нема сенсу повертати стару
-- енергозалежну змінну шкоду заклинань — кожна рівнева форма просто
-- отримує свій ранг кубика.
-- ================================================================

ALTER TABLE spellbook.spells
    ADD COLUMN IF NOT EXISTS damage_die VARCHAR(10);
