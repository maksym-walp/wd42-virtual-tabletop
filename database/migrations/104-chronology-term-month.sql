-- ================================================================
-- Хронологія: власна назва терміну «Місяць».
--
-- calendars.term_month — як цей календар називає «Місяць» (основний поділ
-- року, у якому обирається дата; називний відмінок, однина). NULL —
-- стандартна назва. Для календарів без місяців (наприклад, у дверґів лише
-- сезони й тижні) «місяцем» можна назвати сезон.
-- ================================================================

ALTER TABLE chronology.calendars
    ADD COLUMN IF NOT EXISTS term_month VARCHAR(50);
