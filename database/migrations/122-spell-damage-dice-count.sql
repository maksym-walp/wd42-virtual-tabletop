-- ================================================================
-- Кількість кубиків шкоди заклинання — тепер поле самого заклинання, а не
-- завжди Майстерність кастера (розділ 4.4.3).
--
-- Міграція 120 свідомо прив'язала кількість кубиків шкоди заклинання до
-- Майстерності персонажа, як і для зброї. На практиці ж Майстерність M —
-- це прогрес саме у бою зі зброєю (вузли дерева, target='damage_dice',
-- міграція 112); магія до неї стосунку не має. Тож кожна рівнева форма
-- (основна й forms-JSONB) тепер несе власну кількість кубиків шкоди —
-- автор заклинання задає її прямо, незалежно від дерева розвитку
-- персонажа. NULL/відсутнє значення в старих записах означає 1 (як і
-- раніше), бек-енд завжди нормалізує в ціле число ≥ 1.
-- ================================================================

ALTER TABLE spellbook.spells
    ADD COLUMN IF NOT EXISTS damage_dice_count SMALLINT;
