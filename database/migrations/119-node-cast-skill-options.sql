-- ================================================================
-- Альтернативна навичка чарування — вузли дерева, які текстом
-- описували «кастуєте з кубиком вищої зі своїх навичок: Чарування чи
-- Х», тепер можуть задати це структуровано.
--
-- skill_tree.nodes.cast_skill_options — масив { id, tradition_id,
-- skill_key, note }: для заклинань обраної традиції (spellbook.traditions.id,
-- голий cross-service uuid без FK — як unlocks_traditions) гравець може
-- під час кастування обрати навичку skill_key замість Чарування.
--
-- Навмисно НЕ частина nodes.modifiers (міграція 112): modifiers.target —
-- фіксована навичка, яку підсилює ефект; тут натомість традиція
-- заклинань міняє саму навичку перевірки — інша вісь, інший сенс.
--
-- Два різні вузли одного шляху можуть відкривати різні навички для
-- тієї самої традиції (наприклад «Боржник» → Обман, «Посередник» →
-- Переконливість для традиції «Пакти») — відстежується на рівні
-- вузла, а не традиції чи шляху, тож нічого не хардкодиться в коді.
--
-- Гравець сам обирає, якою навичкою кастувати (character-sheet
-- повертає всі доступні варіанти, вибір — на фронтенді).
-- ================================================================

ALTER TABLE skill_tree.nodes
    ADD COLUMN IF NOT EXISTS cast_skill_options JSONB NOT NULL DEFAULT '[]';
