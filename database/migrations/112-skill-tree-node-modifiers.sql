-- ================================================================
-- Вузлові модифікатори: структурований механічний бік ефекту вузла.
--
-- skill_tree.nodes.effect лишається вільним текстом для опису, а
-- modifiers — те, що система застосовує сама. Масив об'єктів:
--
--   {
--     "id": "<uuid>",        -- стабільний ключ рядка в UI
--     "target": "intuition", -- ключ однієї з 20 навичок або бойова ціль:
--                            -- initiative, attack, damage_dice, death_save,
--                            -- endurance_timer, immunity_check
--     "mode": "adv",         -- adv|dis|wadv|wdis|bal|ext|bonus|rank_up|rank_down
--     "value": 1,            -- bonus: плоский ±N; rank_up/down: рангів;
--                            -- damage_dice: скільки кубиків додати
--     "situational": false,  -- true → не застосовується сам, а пропонується
--                            --        перемикачем у модалці кидка
--     "note": "проти звірів" -- підказка гравцеві, коли саме це діє
--   }
--
-- Згортає модифікатори відкритих вузлів у блок roll_profiles листа
-- character-sheet (src/rules/modifiers.js). Перевага й перешкода з різних
-- джерел складаються або нівелюються за правилом 1.1.4 книги правил.
--
-- Структура навмисно JSONB, а не окрема таблиця: модифікатори завжди
-- читаються й пишуться цілим списком разом із вузлом, як і effect
-- та unlocks_traditions, тож переживають /export і /import без окремого
-- ремапінгу id.
-- ================================================================

ALTER TABLE skill_tree.nodes
    ADD COLUMN IF NOT EXISTS modifiers JSONB NOT NULL DEFAULT '[]'::jsonb;
