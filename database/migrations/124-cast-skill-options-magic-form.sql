-- ================================================================
-- Альтернативна навичка чарування прив'язується до форми магії
-- (spellbook.spells.nature — «Аркана», «Стихії», «Пакт» тощо,
-- admin.site_configs ключ magic_forms), а не до традиції: традиції
-- заклинань більше не керуються з дерева розвитку (міграція 123) і
-- не відкривають ніяких ігрових властивостей напряму.
--
-- skill_tree.nodes.cast_skill_options — масив { id, magic_form,
-- skill_key, note }: для заклинань обраної форми магії (ключ з
-- фіксованого набору ['arcana','elemental','integral','pact','nature','blight'],
-- як і nature — голий рядок без FK) гравець може під час кастування
-- обрати навичку skill_key замість Чарування.
--
-- Старі записи мали поле tradition_id замість magic_form — нова форма
-- несумісна з колишньою (traditions.id — uuid, magic_form — рядок-ключ),
-- тож такі записи скидаються.
-- ================================================================

UPDATE skill_tree.nodes SET cast_skill_options = '[]' WHERE cast_skill_options <> '[]';
